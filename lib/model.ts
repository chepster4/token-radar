// The token radar's model, version radar-2: one snapshot of the protocol universe in, one
// ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and adds
// pre-token protocols below the watchlist floor: the early rows the radar exists to find. A
// protocol is pre-token when its index entry records no token (no market cap, no CoinGecko id,
// no symbol); the snapshot's live-token protocols are kept apart and shown as the market's own
// values, never mixed into the ranked board.
//
// Implied value follows only from the snapshot's own figures, and — unlike a flat multiple —
// it is calibrated on the market itself: for each category, the median market-cap-to-TVL ratio
// of the live-token protocols in that category, shrunk toward the global median so a category
// with one or two listed peers cannot set a wild price, and clamped to a sane band:
//
//   peerMultiple(c) = clamp((n_c * median_c + 5 * globalMedian) / (n_c + 5), 0.05, 1.0)
//   base           = tvl_usd x peerMultiple(category)
//   growth         = clamp(change_7d, -60, 120) per cent
//   growthMult     = 1 + (growth / 100) x GROWTH_WEIGHT
//   maturity       = 0.6 + min(age_days, 1095) / 1095 x 0.4   (age_days unknown: 365)
//   implied        = clamp(round(base x growthMult x maturity), 1, 10^13)
//
// A lending protocol is priced like listed lenders, a DEX like listed DEXes. No protocol name
// is ever special-cased: the same function scores every row, and the calibration table is
// computed from this snapshot at run time, so the model re-prices itself on a new snapshot.
// Each live ratio is winsorized at 2.0x before any median is taken, so one listed protocol
// trading at 400x its TVL cannot set its whole category's price.
//
// Wrapped, staked and bridged products are not launch candidates — WBTC is Bitcoin on
// Ethereum, not a protocol waiting on a token of its own — so the early radar skips them.
// The watchlist itself never contains them by definition, so coverage is unaffected.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
